class employee:
    language = "python"
    salary = 600000
    age = 24

majdoor = employee()
majdoor.name = "siddharth"   #this is a instance attribute, or you can also call it object attribute
print (majdoor.name, majdoor.age, majdoor.language, majdoor.salary)

'''
so here name is a object attribute/instance attribute ,
and age, salary, language, are class attributes
'''